def parse_ref():
    s = open(SRC, encoding="utf-8").read()
    b = s[s.index("const REF: &[Row] = &["):s.index("];", s.index("const REF"))]
    out = {}
    for keys, cat, vals in re.findall(r"\(&\[([^\]]*)\], '(\w)', \[([^\]]*)\]\)", b):
        v = [float(x.strip().rstrip(".")) if x.strip() not in ("",) else 0.0 for x in vals.split(",")]
        for k in re.findall(r'"([^"]+)"', keys):
            out.setdefault(k, v)
    for k, v in EXTRA.items():
        out[k] = [float(x) for x in v]
    return out


def main():
    ref = parse_ref()
    rows = []
    for keys, cat, recipe in DISHES:
        tot = [0.0] * 14
        g = sum(recipe.values())
        assert g <= 100.5, (keys, g)
        for ing, grams in recipe.items():
            v = ref.get(ing)
            assert v is not None, (keys, ing)
            for i in range(14):
                tot[i] += v[i] * grams / 100.0
        rows.append((keys, cat, tot))
    lines = [
        "//! Russian dishes and products for the nutrient estimate (0.19), generated by",
        "//! tools/food/dishes.py from recipes (grams per 100 g of the ready dish) and the reference",
        "//! rows of food_est.rs. Do not edit by hand — change the recipes and run the script.",
        "",
        "/// keys, category (for the per-100-kcal group densities), per 100 g: kcal, protein, carbs, fat,",
        "/// fiber g, K mg, Mg mg, Ca mg, Fe mg, Zn mg, vit C mg, vit A µg RAE, folate µg, B12 µg.",
        "pub const DISHES: &[(&[&str], char, [f64; 14])] = &[",
    ]
    for keys, cat, t in rows:
        ks = ", ".join('"%s"' % k for k in keys)
        vs = ", ".join(("%.2f" % x).rstrip("0").rstrip(".") + ("." if "." not in ("%.2f" % x).rstrip("0").rstrip(".") else "") for x in t)
        lines.append(f"    (&[{ks}], '{cat}', [{vs}]),")
    lines.append("];")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(len(rows), "dishes →", OUT)


if __name__ == "__main__":
    main()
