pub fn group(key: &str) -> Option<(&'static str, &'static str, &'static str)> {
    GROUPS.iter().copied().find(|g| g.0 == key)
}

/// Group of an active ingredient text (may hold several, «ибупрофен+парацетамол»).
pub fn group_of_inn(inn: &str) -> Option<&'static str> {
    let l = inn.to_lowercase();
    INN.iter().find(|(n, _)| l.contains(n)).map(|x| x.1)
}

/// МНН for a trade name from the built-in list.
pub fn inn_of_trade(name: &str) -> Option<&'static str> {
    let l = name.to_lowercase();
    let first = l.split(|c: char| !c.is_alphanumeric()).find(|w| !w.is_empty()).unwrap_or("");
    TRADE.iter().find(|(t, _)| *t == first || l.starts_with(&format!("{t} "))).map(|x| x.1)
}
