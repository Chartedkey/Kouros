/** Раздел по id. */
export function helpSection(id: string): { chapter: HelpChapter; section: HelpSection } | null {
  for (const c of HELP) for (const s of c.sections) if (s.id === id) return { chapter: c, section: s };
  return null;
}

/** Карточка (aria-label) → раздел справки. */
export const CARD_HELP: Record<string, string> = Object.fromEntries(
  HELP.flatMap((c) => c.sections.flatMap((s) => (s.cards ?? []).map((k) => [k, s.id] as const))),
);
